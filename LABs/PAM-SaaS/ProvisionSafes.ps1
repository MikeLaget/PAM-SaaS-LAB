<#
.SYNOPSIS
Overview for Students:
This script represents Infrastructure as Code (IaC). Instead of manually clicking through a web interface to create dozens of folders (Safes) and assigning permissions to dozens of users, we define what the environment should look like in text arrays, and the script builds it exactly as defined.

Key Learning Concepts in this Script:

Data Matrices: Look at $SafesMatrix and $SafeMemberships. These are arrays of hashtables. They act as a configuration blueprint. If you want to add a new Safe to the environment, you don't write new code—you just add a new line to the matrix.
Role-Based Access Control (RBAC) Mapping: The $PermissionProfiles hashtable translates human-friendly roles (like "VaultAdmin" or "ConnectOnly") into the exact true/false API flags the PAM backend requires (like useAccounts=$true, deleteAccounts=$false).
The Execution Flow:
1. It reads the CSV file generated by Script 1 to know who is logging in.
2. It authenticates to the API.
3. It iterates through the $SafesMatrix to create the storage containers.
4. It iterates through the $SafeMemberships matrix to attach users and Active Directory groups to those Safes with precise permissions.
5. Least Privilege Cleanup: Finally, it removes the administrator account (the one running the script) from the Safes, ensuring that admins don't retain permanent backdoor access to secure vaults.
