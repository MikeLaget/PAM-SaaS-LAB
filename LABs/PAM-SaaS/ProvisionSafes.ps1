# Config
$global:EnableFileLogging = $true
$global:EnableDebugMode   = $false
$global:LogFilePath = Join-Path -Path ([Environment]::GetFolderPath("Desktop")) -ChildPath "PAM_Provisioning_$(Get-Date -Format 'yyyyMMdd_HHmmss').log"

